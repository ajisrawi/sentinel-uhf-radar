"""Run with KiCad's Python: build SENTINEL_TRM.kicad_pcb from plan.json and fill zones."""
import json
import sys
from pathlib import Path

import pcbnew

HERE = Path(sys.argv[1]).resolve()
NAME = sys.argv[2]
FP_ROOT = Path(r"C:\Program Files\KiCad\10.0\share\kicad\footprints")
MM = pcbnew.FromMM
LAYER = {"F.Cu": pcbnew.F_Cu, "In1.Cu": pcbnew.In1_Cu, "In2.Cu": pcbnew.In2_Cu, "B.Cu": pcbnew.B_Cu}


def pt(x, y):
    return pcbnew.VECTOR2I(MM(x), MM(y))


def main():
    plan = json.loads((HERE / "plan.json").read_text())
    W, H = plan["size"]
    board = pcbnew.BOARD()
    board.SetCopperLayerCount(4)
    ds = board.GetDesignSettings()
    ds.m_MinClearance = MM(0.2)
    ds.m_TrackMinWidth = MM(0.2)
    ds.m_ViasMinSize = MM(0.6)
    ds.m_MinThroughDrill = MM(0.3)
    ds.m_CopperEdgeClearance = MM(0.3)
    ds.m_HoleToHoleMin = MM(0.25)
    tb = board.GetTitleBlock()
    tb.SetTitle(plan.get("title", NAME))
    tb.SetRevision("A")
    tb.SetDate("2026-10-18")
    tb.SetComment(0, "First-pass layout generated by pcb_plan.py - not released for fabrication")
    tb.SetComment(1, "4L: F.Cu / In1 GND / In2 power+signal / B.Cu signal")

    nets = {}

    def net(name):
        if name not in nets:
            ni = pcbnew.NETINFO_ITEM(board, name)
            board.Add(ni)
            nets[name] = ni
        return nets[name]

    ns = ds.m_NetSettings
    for name, clr, tw, pattern in plan.get("netclasses", []):
        nc = pcbnew.NETCLASS(name)
        nc.SetClearance(MM(clr))
        nc.SetTrackWidth(MM(tw))
        ns.SetNetclass(name, nc)
        ns.SetNetclassPatternAssignment(pattern, name)
    padnet = {(r, p): n for r, p, n in plan["padnets"]}
    for name in sorted(set(padnet.values())):
        net(name)

    # board outline
    rect = pcbnew.PCB_SHAPE(board)
    rect.SetShape(pcbnew.SHAPE_T_RECT)
    rect.SetStart(pt(0, 0))
    rect.SetEnd(pt(W, H))
    rect.SetLayer(pcbnew.Edge_Cuts)
    rect.SetWidth(MM(0.1))
    board.Add(rect)

    for p in plan["parts"]:
        lib, name = p["fp"].split(":")
        path = str(HERE / "SENTINEL.pretty") if lib == "SENTINEL" else str(FP_ROOT / f"{lib}.pretty")
        fp = pcbnew.FootprintLoad(path, name)
        fp.SetFPIDAsString(p["fp"])
        fp.SetReference(p["ref"])
        fp.SetValue(p["value"])
        if p["tstamp"]:
            fp.SetPath(pcbnew.KIID_PATH(f"/{p['tstamp']}"))
        board.Add(fp)
        fp.SetPosition(pt(p["x"], p["y"]))
        fp.SetOrientationDegrees(p["rot"])
        for pad in fp.Pads():
            n = padnet.get((p["ref"], pad.GetNumber()))
            if n:
                pad.SetNet(net(n))

    print("footprints ok", flush=True)
    for layer, a, b, w, n in plan["tracks"]:
        t = pcbnew.PCB_TRACK(board)
        t.SetStart(pt(*a))
        t.SetEnd(pt(*b))
        t.SetWidth(MM(w))
        t.SetLayer(LAYER[layer])
        t.SetNet(net(n))
        board.Add(t)

    print("tracks ok", flush=True)
    for x, y, d, dr, n in plan["vias"]:
        v = pcbnew.PCB_VIA(board)
        v.SetPosition(pt(x, y))
        v.SetWidth(MM(d))
        v.SetDrill(MM(dr))
        v.SetNet(net(n))
        board.Add(v)

    print("vias ok", flush=True)
    for z in plan["zones"]:
        for poly in z["polys"]:
            zone = pcbnew.ZONE(board)
            zone.SetLayer(LAYER[z["layer"]])
            zone.SetNet(net(z["net"]))
            zone.SetAssignedPriority(z["priority"])
            zone.SetLocalClearance(MM(0.3))
            zone.SetMinThickness(MM(0.25))
            zone.SetPadConnection(pcbnew.ZONE_CONNECTION_FULL)
            zone.SetThermalReliefGap(MM(0.3))
            zone.SetThermalReliefSpokeWidth(MM(0.4))
            zone.SetIslandRemovalMode(pcbnew.ISLAND_REMOVAL_MODE_ALWAYS)
            ol = zone.Outline()
            ol.NewOutline()
            for x, y in poly[0][:-1]:
                ol.Append(MM(x), MM(y))
            for hole in poly[1:]:
                ol.NewHole()
                for x, y in hole[:-1]:
                    ol.Append(MM(x), MM(y), 0, ol.HoleCount(0) - 1)
            board.Add(zone)

    print("zones ok", flush=True)
    # zones are filled by kicad-cli (drc --refill-zones --save-board); the in-process
    # filler crashes without a GUI progress reporter in KiCad 10
    board.BuildConnectivity()
    out = HERE / f"{NAME}.kicad_pcb"
    pcbnew.SaveBoard(str(out), board)
    print("saved", out.name, "footprints", len(plan["parts"]), "tracks", len(plan["tracks"]),
          "vias", len(plan["vias"]), "zones", board.GetAreaCount())


if __name__ == "__main__":
    main()
